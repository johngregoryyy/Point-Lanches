-- 1. Categorias
CREATE TABLE IF NOT EXISTS public.categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL UNIQUE,
    ordem INT DEFAULT 0
);

-- 2. Produtos
CREATE TABLE IF NOT EXISTS public.produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT NOT NULL REFERENCES public.categorias(id) ON DELETE RESTRICT,
    nome TEXT NOT NULL,
    descricao TEXT DEFAULT '',
    preco NUMERIC(10, 2) NOT NULL,
    ativo INT DEFAULT 1
);

-- 3. Adicionais / Extras
CREATE TABLE IF NOT EXISTS public.adicionais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    preco NUMERIC(10, 2) NOT NULL,
    ativo INT DEFAULT 1
);

-- 4. Taxas de Entrega
CREATE TABLE IF NOT EXISTS public.taxas_entrega (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor NUMERIC(10, 2) NOT NULL,
    label TEXT NOT NULL,
    ativo INT DEFAULT 1,
    ordem INT DEFAULT 0
);

-- 5. Observações Rápidas
CREATE TABLE IF NOT EXISTS public.observacoes_padrao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto TEXT NOT NULL,
    ativo INT DEFAULT 1
);

-- 6. Ruas e Bairros
CREATE TABLE IF NOT EXISTS public.ruas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL UNIQUE,
    ativo INT DEFAULT 1,
    bairro TEXT DEFAULT '',
    taxa NUMERIC(10, 2) DEFAULT 0.0
);

-- 7. Configurações Gerais
CREATE TABLE IF NOT EXISTS public.configuracoes (
    chave TEXT PRIMARY KEY,
    valor TEXT NOT NULL
);

-- 8. Pedidos
CREATE TABLE IF NOT EXISTS public.pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero INT NOT NULL,
    cliente_nome TEXT DEFAULT '',
    cliente_fone TEXT DEFAULT '',
    endereco_rua TEXT DEFAULT '',
    endereco_num TEXT DEFAULT '',
    endereco_comp TEXT DEFAULT '',
    endereco_bairro TEXT DEFAULT '',
    endereco_ref TEXT DEFAULT '',
    subtotal NUMERIC(10, 2) DEFAULT 0,
    taxa_entrega NUMERIC(10, 2) DEFAULT 0,
    total NUMERIC(10, 2) DEFAULT 0,
    forma_pgto TEXT DEFAULT '',
    valor_pago NUMERIC(10, 2) DEFAULT 0,
    troco NUMERIC(10, 2) DEFAULT 0,
    status TEXT DEFAULT 'aberto',
    criado_em TIMESTAMPTZ DEFAULT NOW()
);

-- 9. Itens do Pedido
CREATE TABLE IF NOT EXISTS public.itens_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES public.pedidos(id) ON DELETE CASCADE,
    produto_id BIGINT REFERENCES public.produtos(id) ON DELETE SET NULL,
    nome TEXT NOT NULL,
    preco_unit NUMERIC(10, 2) NOT NULL,
    quantidade INT NOT NULL DEFAULT 1,
    observacao TEXT DEFAULT '',
    categoria TEXT DEFAULT ''
);

-- 10. Insumos (Estoque e Lucro)
CREATE TABLE IF NOT EXISTS public.insumos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    unidade_medida TEXT NOT NULL,
    custo_unitario NUMERIC(10, 2) NOT NULL DEFAULT 0.0,
    estoque_atual NUMERIC(10, 2) NOT NULL DEFAULT 0.0,
    ativo INT DEFAULT 1
);

-- 11. Movimentações de Insumos
CREATE TABLE IF NOT EXISTS public.movimentacoes_insumos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    insumo_id BIGINT NOT NULL REFERENCES public.insumos(id) ON DELETE CASCADE,
    tipo TEXT NOT NULL,
    quantidade NUMERIC(10, 2) NOT NULL,
    valor_total NUMERIC(10, 2) NOT NULL,
    data TEXT NOT NULL
);

-- 12. Histórico de Endereços (Frete Inteligente)
CREATE TABLE IF NOT EXISTS public.historico_enderecos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rua TEXT NOT NULL,
    numero TEXT NOT NULL,
    bairro TEXT DEFAULT '',
    taxa_frete NUMERIC(10, 2) NOT NULL DEFAULT 0.0,
    atualizado_em TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT uq_historico_rua_numero UNIQUE(rua, numero)
);

-- =============================================================================
-- PERMISSÕES E ACESSO DIRETO PARA O APLICATIVO
-- =============================================================================
ALTER TABLE public.categorias DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.produtos DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.adicionais DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.taxas_entrega DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.observacoes_padrao DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.ruas DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.configuracoes DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.pedidos DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.itens_pedido DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.insumos DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.movimentacoes_insumos DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.historico_enderecos DISABLE ROW LEVEL SECURITY;

GRANT ALL ON ALL TABLES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
